// Expo config plugin (BUG-003): redraws the home-screen widgets just after midnight.
// One inexact setWindow alarm (10-min window) per night; never uses the exact-alarm permission.
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withMainApplication,
} = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const RECEIVER = '.widget.WidgetMidnightReceiver';

function receiverSource(pkg, providers) {
  return `package ${pkg}.widget

import android.app.AlarmManager
import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.content.BroadcastReceiver
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import java.util.Calendar

/**
 * Generated by plugins/with-widget-midnight.js (BUG-003). Do not edit by hand.
 * At 00:01 local time it asks every placed Pebblesip widget to redraw (the JS task handler
 * reads today's totals from SQLite), then sets the alarm for the next night.
 * Re-scheduled on boot, clock/timezone change, app update and every app process start.
 */
class WidgetMidnightReceiver : BroadcastReceiver() {
  override fun onReceive(context: Context, intent: Intent) {
    if (intent.action == ACTION_MIDNIGHT || intent.action == Intent.ACTION_TIME_CHANGED ||
      intent.action == Intent.ACTION_TIMEZONE_CHANGED) {
      refreshAll(context)
    }
    schedule(context)
  }

  companion object {
    const val ACTION_MIDNIGHT = "${pkg}.WIDGET_MIDNIGHT"
    private const val WINDOW_MS = 10 * 60 * 1000L
    private val PROVIDERS = listOf(${providers.map((p) => `${p}::class.java`).join(', ')})

    private fun widgetIds(context: Context, provider: Class<*>): IntArray =
      AppWidgetManager.getInstance(context).getAppWidgetIds(ComponentName(context, provider))

    fun refreshAll(context: Context) {
      for (provider in PROVIDERS) {
        val ids = widgetIds(context, provider)
        if (ids.isEmpty()) continue
        context.sendBroadcast(
          Intent(context, provider)
            .setAction(AppWidgetManager.ACTION_APPWIDGET_UPDATE)
            .putExtra(AppWidgetManager.EXTRA_APPWIDGET_IDS, ids)
        )
      }
    }

    /** Sets (or replaces) the single inexact alarm for 00:01 tomorrow. No-op without widgets. */
    @JvmStatic
    fun schedule(context: Context) {
      val alarms = context.getSystemService(Context.ALARM_SERVICE) as AlarmManager
      val pending = PendingIntent.getBroadcast(
        context,
        0,
        Intent(context, WidgetMidnightReceiver::class.java).setAction(ACTION_MIDNIGHT),
        PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
      )
      if (PROVIDERS.all { widgetIds(context, it).isEmpty() }) {
        alarms.cancel(pending)
        return
      }
      val next = Calendar.getInstance().apply {
        add(Calendar.DAY_OF_YEAR, 1)
        set(Calendar.HOUR_OF_DAY, 0)
        set(Calendar.MINUTE, 1)
        set(Calendar.SECOND, 0)
        set(Calendar.MILLISECOND, 0)
      }
      // Inexact 10-minute window (the shortest Android allows without exact-alarm access).
      alarms.setWindow(AlarmManager.RTC_WAKEUP, next.timeInMillis, WINDOW_MS, pending)
    }
  }
}
`;
}

module.exports = function withWidgetMidnight(config, { widgets = [] } = {}) {
  const pkg = config.android?.package;
  if (!pkg) throw new Error('with-widget-midnight: android.package is required');

  config = withAndroidManifest(config, (c) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    app.receiver = (app.receiver ?? []).filter((r) => r.$['android:name'] !== RECEIVER);
    app.receiver.push({
      $: { 'android:name': RECEIVER, 'android:exported': 'false' },
      'intent-filter': [
        {
          action: [
            `${pkg}.WIDGET_MIDNIGHT`,
            'android.intent.action.BOOT_COMPLETED',
            'android.intent.action.MY_PACKAGE_REPLACED',
            'android.intent.action.TIME_SET',
            'android.intent.action.TIMEZONE_CHANGED',
          ].map((n) => ({ $: { 'android:name': n } })),
        },
      ],
    });
    const perms = (c.modResults.manifest['uses-permission'] ??= []);
    if (!perms.some((p) => p.$['android:name'] === 'android.permission.RECEIVE_BOOT_COMPLETED')) {
      perms.push({ $: { 'android:name': 'android.permission.RECEIVE_BOOT_COMPLETED' } });
    }
    return c;
  });

  config = withDangerousMod(config, [
    'android',
    (c) => {
      const dir = path.join(
        c.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...pkg.split('.'),
        'widget',
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'WidgetMidnightReceiver.kt'), receiverSource(pkg, widgets));
      return c;
    },
  ]);

  // Any app process start (app open, widget tap, notification action) re-arms the alarm.
  config = withMainApplication(config, (c) => {
    const line = `    ${pkg}.widget.WidgetMidnightReceiver.schedule(this)`;
    if (!c.modResults.contents.includes('WidgetMidnightReceiver.schedule')) {
      c.modResults.contents = c.modResults.contents.replace(
        /(override fun onCreate\(\) \{\n\s*super\.onCreate\(\)\n)/,
        `$1${line}\n`,
      );
    }
    return c;
  });

  return config;
};
